"""Doorloop in Edge met Playwright, voor test.py --browser. Schermafbeeldingen komen in test/uit/ (niet in git).
PDF.js komt van cdnjs: deze test heeft internet nodig."""
from pathlib import Path

from playwright.sync_api import sync_playwright


def doorloop(url, startcode, uit: Path):
    uit.mkdir(exist_ok=True)
    fouten = []
    res = []

    def check(naam, ok, uitleg=""):
        res.append((naam, bool(ok), uitleg))

    with sync_playwright() as p:
        br = p.chromium.launch(channel="msedge")

        def nieuw(**kw):
            c = br.new_context(viewport={"width": 1400, "height": 900}, **kw)
            pg = c.new_page()
            pg.on("pageerror", lambda e: fouten.append(str(e)))
            pg.on("console", lambda m: m.type == "error" and fouten.append(m.text))
            return c, pg

        # zonder account: de boekenkast en het handboek lezen, geen feedback
        cg, g = nieuw()
        g.goto(url)
        g.wait_for_selector(".kast")
        g.wait_for_function("[...document.querySelectorAll('.boek img')].slice(0, 6).every(i => i.complete && i.naturalWidth > 0)")
        g.screenshot(path=uit / "00-gast-kast.png")
        check("browser: zonder account de boekenkast", g.locator(".boek img").count() > 20)
        g.click("a.boek:has(img) >> nth=0")
        g.wait_for_selector(".boekkop")
        check("browser: zonder account alleen het handboek", g.locator(".editie").count() == 1 and g.locator(".fb, textarea").count() == 0)
        g.screenshot(path=uit / "00-gast-boek.png")
        g.click("a:has-text('Lees') >> nth=0")
        g.wait_for_selector(".blad canvas.geladen", timeout=30000)
        check("browser: zonder account lezen, zonder markeerstift", g.locator("button.markeer").count() == 0)
        g.screenshot(path=uit / "00-gast-lezer.png")
        # de kaders "Verwerkt" (verwerkt.yaml): een boek waarvan de versie er heeft, op de pagina van het eerste
        doel = g.evaluate("""async () => {
          const d = await (await fetch('/api/index.php?r=boeken')).json();
          for (const b of d.boeken) for (const e of b.edities.filter((e) => e.editie === 'handboek')) {
            const v = await (await fetch('/api/index.php?r=versie/' + e.hash)).json();
            if (v.verwerkt && v.verwerkt.length) return [e.hash, v.verwerkt[0].pagina];
          }
          return null; }""")
        if doel:
            g.goto(f"{url}#/lees/{doel[0]}?p={doel[1]}")
            g.wait_for_selector(".verwerkt-kader", timeout=30000)
            g.wait_for_timeout(800)
            g.locator(".verwerkt-kader").first.scroll_into_view_if_needed()
            g.screenshot(path=uit / "00-gast-verwerkt.png")
            g.click("button[aria-label='Paneel met de inhoud']")  # zonder paneel: de kaders naast de pagina
            g.wait_for_timeout(600)
            g.locator(".verwerkt-kader").first.scroll_into_view_if_needed()
            g.screenshot(path=uit / "00-gast-verwerkt-ruim.png")
            check("browser: kaders Verwerkt naast de pagina", g.locator(".vel.ruim").count() == 1)
            check("browser: kaders Verwerkt in de lezer", g.locator(".verwerkt-kader").count() > 0 and g.locator(".verwerkt-lijn").count() > 0)
            g.click("button.verwerkt-knop")
            check("browser: kaders Verwerkt uit te zetten", g.locator(".verwerkt-kader").count() == 0)
            g.click("button.verwerkt-knop")
        g.goto(url + "/#/mijn")
        g.wait_for_selector(".welkom")
        check("browser: zonder account naar aanmelden bij mijn feedback", True)
        g.goto(url + "/#/plannen")
        g.wait_for_selector(".plannen")
        check("browser: plannen met zes voorproefjes", g.locator(".proef").count() == 6)
        g.screenshot(path=uit / "00-gast-plannen.png", full_page=True)
        # koepel en richting: GO! geeft Grieks-Latijn (3de graad) de handboeken van pakket 2 en Telproblemen
        g.goto(url + "/#/")
        g.wait_for_selector(".koepel-rij")
        g.click(".koepel-rij button:has-text('GO!')")
        g.select_option(".richting-keuze", "3|Grieks-Latijn")
        g.wait_for_selector("h2:has-text('Verplichte handboeken')")
        check("browser: GO! Grieks-Latijn met pakket 2 en Telproblemen",
              g.locator("a.boek[href*='2%2FAnalyse%2FIntegralen']").count() == 1 and g.locator("a.boek[href*='Telproblemen']").count() == 1)
        check("browser: per voorgesteld leerjaar", g.locator(".jaar-kop").count() >= 2)
        g.screenshot(path=uit / "00-gast-go-richting.png", full_page=True)
        g.click("a.boek[href*='2%2FAnalyse%2FIntegralen']")
        g.wait_for_selector(".boekkop")
        check("browser: richtingen volgens GO! op het boek", "Grieks-Latijn" in g.locator(".gegevens").inner_text())
        with g.expect_download(timeout=90000) as dl:
            g.click(".editie button:has-text('PDF')")
        try:
            import pymupdf
            with pymupdf.open(dl.value.path()) as doc:
                tekst = doc[0].get_text()
            check("browser: PDF met de voorkant van GO!", "Richtingen met wiskunde voor economie" in tekst, tekst[-200:])
        except ImportError:
            check("browser: PDF met de voorkant van GO!", dl.value.suggested_filename.endswith("(GO!).pdf"), dl.value.suggested_filename)
        g.screenshot(path=uit / "00-gast-go-boek.png")
        # dubbele finaliteit en arbeidsmarkt: een D/A-richting (KOV) en het handboek op aanvraag
        g.goto(url + "/#/")
        g.wait_for_selector(".koepel-rij")
        g.click(".koepel-rij button:has-text('Katholiek')")
        g.select_option(".richting-keuze", "3|Bouwtechnieken")
        g.wait_for_selector("h2:has-text('Verplichte handboeken')")
        check("browser: D/A Bouwtechnieken met de 7 handboeken van pakket 6",
              g.locator(".kast a.boek[href*='6%2F']").count() == 7 and "dubbele finaliteit" in g.locator(".pakket-sub").first.inner_text())
        g.screenshot(path=uit / "00-gast-da-richting.png", full_page=True)
        g.click("button:has-text('Toon weer alles')")
        g.click(".chips button:has-text('2de graad')")
        g.click(".fin-rij button:has-text('Arbeidsmarktfinaliteit')")
        g.wait_for_selector(".interesse")
        check("browser: arbeidsmarkt op aanvraag, met de vraag om interesse",
              g.locator(".pakket").count() == 1 and g.locator(".interesse").count() == 1)
        g.screenshot(path=uit / "00-gast-a-interesse.png", full_page=True)
        g.click(".fin-rij button:has-text('Alle finaliteiten')")
        g.click(".chips button:has-text('Alle graden')")
        cg.close()

        # beheerder met de startcode
        cb, b = nieuw()
        b.goto(url + "/#/aanmelden")
        b.wait_for_selector(".welkom")
        b.screenshot(path=uit / "01-welkom.png")
        b.click("button[data-k=uitnodiging]")
        b.fill("input[placeholder='abcd-efgh-jkmn']", startcode)
        b.fill("input[autocomplete=name]", "Team Lid")
        b.fill("input[autocomplete=email]", "team@voorbeeld.be")
        b.fill("input[autocomplete=new-password]", "geheim-wachtwoord")
        b.click("button:has-text('Account maken')")
        # een nieuw account gaat meteen naar de lesopdracht; de beheerder kiest 'Later'
        b.wait_for_selector(".profiel")
        check("browser: nieuw account gaat naar de lesopdracht", "Welkom" in b.locator("h1").inner_text())
        # zonder in te vullen opnieuw naar de site: een bestaand account krijgt de vraag in een venster
        b.goto(url + "/?opnieuw=1#/")
        b.wait_for_selector("dialog[open]:has-text('Waar geef je les?')")
        check("browser: vraag naar de lesopdracht voor een bestaand account", True)
        b.screenshot(path=uit / "01b-vraag-lesopdracht.png")
        b.click("dialog[open] button:has-text('Later')")
        b.wait_for_selector(".kast")
        b.wait_for_function("[...document.querySelectorAll('.boek img')].slice(0, 6).every(i => i.complete && i.naturalWidth > 0)")
        b.screenshot(path=uit / "02-kast.png")
        check("browser: boekenkast met voorkanten", b.locator(".boek img").count() > 20)

        b.goto(url + "/#/beheer/mensen")
        b.wait_for_selector("input[type=number]")
        b.click("button:has-text('Maak codes')")
        b.wait_for_selector(".code code")
        code = b.locator(".code code").first.inner_text()
        check("browser: uitnodigingscode gemaakt", len(code) == 14, code)
        b.fill("input[placeholder^='Voor wie']", "Ingmar")
        b.click("button:has-text('Maak sleutel')")
        b.wait_for_selector("dialog[open] code")
        sl = b.locator("dialog[open] code").last.inner_text()
        check("browser: sleutel voor Claude", sl.startswith("axm-"), sl)
        b.screenshot(path=uit / "02b-sleutel.png")
        b.click("dialog[open] button:has-text('Sluit')")
        b.wait_for_selector("button:has-text('Intrekken')")
        b.screenshot(path=uit / "02c-mensen.png", full_page=True)

        # leerkracht via de link met code
        cl, l = nieuw()
        l.goto(f"{url}/#/?code={code}")
        l.wait_for_selector(".welkom")
        l.fill("input[autocomplete=name]", "An Leerkracht")
        l.fill("input[autocomplete=email]", "an@voorbeeld.be")
        l.fill("input[autocomplete=new-password]", "nog-een-wachtwoord")
        l.click("button:has-text('Account maken')")
        # de lesopdracht: koepel, leerjaren, finaliteit, en dan verschijnen de richtingen
        l.wait_for_selector(".profiel")
        l.click(".profiel .chip:has-text('Katholiek')")
        l.click(".profiel .chip:has-text('5de jaar')")
        l.click(".profiel .chip:has-text('6de jaar')")
        l.click(".profiel .chip:has-text('Doorstroom')")
        l.wait_for_selector(".richting-groep")
        l.locator(".vinkje:has-text('Latijn-Wiskunde') input").check()
        l.screenshot(path=uit / "02d-lesopdracht.png", full_page=True)
        l.click(".profiel button:has-text('Bewaar')")
        l.wait_for_selector(".kast")
        check("browser: lesopdracht bewaard", l.evaluate("fetch('/api/index.php?r=profiel').then(r => r.json()).then(p => p.richtingen.join())") == "3|Latijn-Wiskunde")
        l.click("a.boek >> nth=0")
        l.wait_for_selector(".boekkop")
        l.click(".chip.s-didactiek")
        l.fill(".kaart textarea", "Het tempo in hoofdstuk 2 ligt hoog voor pakket 1.")
        l.click("button:has-text('Verstuur')")
        l.wait_for_selector(".fb")
        check("browser: feedback op het handboek", "tempo" in l.locator(".fb").first.inner_text())
        l.screenshot(path=uit / "03-boek.png")

        # lezer met PDF.js
        l.click("a:has-text('Lees en geef feedback') >> nth=0")
        l.wait_for_selector(".blad canvas.geladen", timeout=30000)
        check("browser: PDF.js tekent de pagina's", l.locator(".blad canvas.geladen").count() >= 1)
        l.locator(".blad").nth(1).scroll_into_view_if_needed()
        l.wait_for_selector(".blad[data-n='2'] canvas.geladen", timeout=15000)
        box = l.locator(".blad").nth(1).bounding_box()
        l.mouse.move(box["x"] + box["width"] * .15, box["y"] + box["height"] * .2)
        l.mouse.down()
        l.mouse.move(box["x"] + box["width"] * .7, box["y"] + box["height"] * .3, steps=8)
        l.mouse.up()
        l.wait_for_selector(".nieuw")
        l.wait_for_function("document.querySelector('.nieuw .citaat') && document.querySelector('.nieuw .citaat').textContent !== '…'")
        citaat = l.locator(".nieuw .citaat").inner_text()
        check("browser: citaat uit de tekstlaag", len(citaat) > 5 and "(geen tekst" not in citaat, citaat)
        l.screenshot(path=uit / "04-nieuw.png")
        l.click(".nieuw .chip.s-taal")
        l.fill(".nieuw textarea", "Spatie te veel in de tweede zin.")
        l.click(".nieuw button:has-text('Bewaar')")
        l.wait_for_selector(".markering")
        l.mouse.click(box["x"] + box["width"] * .5, box["y"] + box["height"] * .6)
        l.wait_for_selector(".nieuw")
        l.click(".nieuw .chip.s-fout")
        l.click(".nieuw .segment button:has-text('Dringend')")
        l.fill(".nieuw textarea", "Hier hoort een min.")
        l.click(".nieuw button:has-text('Bewaar')")
        l.wait_for_function("document.querySelectorAll('.markering').length === 2")
        check("browser: twee markeringen op de pagina", l.locator(".markering").count() == 2)
        l.wait_for_timeout(400)
        l.screenshot(path=uit / "05-lezer.png")
        l.keyboard.press("m")
        l.click("button[aria-label=Groter]")
        l.wait_for_timeout(800)
        l.screenshot(path=uit / "06-zoom.png")
        l.click(".tabs button[data-k=inhoud]")
        l.locator(".inhoud-lijst button").nth(3).click()
        l.wait_for_timeout(800)
        check("browser: inhoudstafel springt naar een pagina", int(l.locator(".paginanr input").input_value()) > 2)

        l.goto(url + "/#/algemeen")
        l.wait_for_selector(".kaart textarea")
        l.fill(".kaart textarea", "Mooi idee, maar voorzie ook digitale toetsen.")
        l.click("button:has-text('Verstuur')")
        l.wait_for_selector(".fb")

        # beheerder antwoordt en exporteert
        b.goto(url + "/#/beheer")
        b.wait_for_selector(".fb")
        check("browser: beheer toont 4 open opmerkingen", b.locator(".fb").count() == 4)
        b.locator(".fb textarea").first.fill("Dank je, we passen het aan.")
        b.locator(".fb button:has-text('Stuur')").first.click()
        b.wait_for_timeout(500)
        b.screenshot(path=uit / "07-beheer.png", full_page=True)
        # goedkeuren en afkeuren met knoppen, en het logboek
        check("browser: elke nieuwe opmerking heeft Goedkeuren en Afkeuren", b.locator(".fb button:has-text('Goedkeuren')").count() == 4
              and b.locator(".fb button:has-text('Afkeuren')").count() == 4)
        b.locator(".fb button:has-text('Goedkeuren')").first.click()
        b.wait_for_timeout(600)
        check("browser: goedgekeurd: knop Zet op verwerkt", b.locator(".fb button:has-text('Zet op verwerkt')").count() == 1
              and b.locator(".fb .st-behandeling:has-text('Goedgekeurd')").count() == 1)
        b.locator(".fb button:has-text('Afkeuren')").first.click()
        b.locator("dialog textarea").fill("Dit laten we zo.")
        b.locator("dialog button:has-text('Afkeuren')").click()
        b.wait_for_timeout(600)
        b.goto(url + "/#/beheer/logboek")
        b.wait_for_selector(".logkaart")
        tekst = b.locator(".lijst").inner_text()
        check("browser: logboek toont goed- en afkeuren", "Nieuw → Goedgekeurd" in tekst and "→ Afgekeurd" in tekst and "Dit laten we zo." in tekst, tekst[:300])
        b.screenshot(path=uit / "07b-logboek.png", full_page=True)
        # het werkplan: de derde TODO naar boven slepen, aan de greep
        b.goto(url + "/#/beheer/werkplan")
        b.wait_for_selector(".werkplan > li")
        b.screenshot(path=uit / "07c-werkplan.png", full_page=True)
        voor = b.eval_on_selector_all(".werkplan > li", "l => l.map(x => x.dataset.sleutel)")
        greep, doel = b.locator(".werkplan > li .greep").nth(2).bounding_box(), b.locator(".werkplan > li").nth(0).bounding_box()
        b.mouse.move(greep["x"] + 16, greep["y"] + 16)
        b.mouse.down()
        for i in range(1, 11):
            b.mouse.move(greep["x"] + 16, greep["y"] + 16 + (doel["y"] + 5 - greep["y"] - 16) * i / 10)
        b.screenshot(path=uit / "07d-werkplan-slepen.png")
        b.mouse.up()
        b.wait_for_timeout(600)
        na = b.evaluate("fetch('/api/index.php?r=beheer/werkplan').then(r => r.json()).then(d => d.items.map(i => i.sleutel))")
        check("browser: werkplan slepen en bewaren", na[:3] == [voor[2], voor[0], voor[1]] and sorted(na) == sorted(voor), (voor[:3], na[:3], len(voor), len(na)))
        b.locator(".werkplan > li .greep").nth(0).focus()
        b.keyboard.press("ArrowDown")
        b.wait_for_timeout(600)
        na = b.evaluate("fetch('/api/index.php?r=beheer/werkplan').then(r => r.json()).then(d => d.items.map(i => i.sleutel))")
        check("browser: werkplan met de pijltjes", na[:2] == [voor[0], voor[2]], na[:3])
        b.locator(".werkplan details").first.evaluate("d => d.open = true")
        b.screenshot(path=uit / "07e-werkplan-open.png", full_page=True)
        # Ingmar omzetten, zelf een TODO schrijven en feedback geven
        knop = b.locator(".werkplan > li").nth(1).locator(".wp-ingmar")
        was = knop.get_attribute("aria-pressed")
        knop.click()
        b.wait_for_timeout(500)
        check("browser: werkplan Ingmar omzetten", b.locator(".werkplan > li").nth(1).locator(".wp-ingmar").get_attribute("aria-pressed") != was)
        b.click("button:has-text('Nieuwe TODO')")
        b.fill(".wp-nieuwe input[type=text]", "Een TODO van de site")
        b.fill(".wp-nieuwe textarea", "- eerst dit\n- dan **dat**")
        b.screenshot(path=uit / "07f-werkplan-nieuw.png")
        b.click(".wp-nieuwe button[type=submit]")
        b.wait_for_timeout(600)
        check("browser: werkplan eigen TODO bovenaan", "Een TODO van de site" in b.locator(".werkplan > li").first.inner_text())
        eerste = b.locator(".werkplan > li").first
        eerste.locator("summary:has-text('Feedback')").click()
        eerste.locator(".reageer textarea").fill("Dit eerst afwerken.")
        eerste.locator(".reageer button").click()
        b.wait_for_timeout(600)
        eerste = b.locator(".werkplan > li").first
        check("browser: werkplan feedback geven", "Feedback (1)" in eerste.inner_text() and "Dit eerst afwerken." in eerste.inner_text(), eerste.inner_text()[:300])
        eerste.locator("summary:has-text('Wat er nog')").click()
        b.screenshot(path=uit / "07g-werkplan-feedback.png")
        b.goto(url + "/#/beheer")
        b.wait_for_selector(".fb")
        md = b.evaluate("fetch('/api/index.php?r=beheer/export&formaat=md').then(r => r.text())")
        (uit / "export.md").write_text(md, encoding="utf-8")
        check("browser: export bevat het citaat", "> " in md and "Spatie te veel" in md, md[:200])
        b.goto(url + "/#/beheer/overzicht")
        b.wait_for_selector("table")
        b.screenshot(path=uit / "08-overzicht.png")
        b.goto(url + "/#/beheer/dekking")
        b.wait_for_selector(".dekking-groep")
        tekst = b.locator(".pagina").inner_text()
        check("browser: dekking toont de richting van de leerkracht", "Latijn-Wiskunde" in tekst and "richtingen met een leerkracht" in tekst, tekst[:300])
        b.screenshot(path=uit / "08b-dekking.png", full_page=True)
        # een bestaand account zonder lesopdracht krijgt de vraag bij een nieuw bezoek (na 'Later' pas na een week)
        b.evaluate("fetch('/api/index.php?r=profiel/later', {method: 'POST', headers: {'X-Axiomath': '1'}})")
        b.reload()
        b.wait_for_selector(".kast, .fb, table")
        check("browser: na 'Later' geen vraag", b.locator("dialog[open]").count() == 0)

        l.goto(url + "/#/mijn")
        l.wait_for_selector(".reactie.team")
        check("browser: leerkracht ziet het antwoord", True)
        l.emulate_media(color_scheme="dark")
        l.screenshot(path=uit / "09-mijn-donker.png", full_page=True)

        cm = br.new_context(viewport={"width": 390, "height": 844}, storage_state=cl.storage_state(), is_mobile=True, has_touch=True)
        m = cm.new_page()
        m.on("pageerror", lambda e: fouten.append(str(e)))
        m.goto(url)
        m.wait_for_selector(".kast")
        m.wait_for_timeout(1000)
        m.screenshot(path=uit / "10-gsm-kast.png")
        check("browser: geen horizontaal scrollen op gsm", m.evaluate("document.documentElement.scrollWidth") <= 390)
        m.click("a.boek >> nth=0")
        m.click("a:has-text('Lees en geef feedback') >> nth=0")
        m.wait_for_selector(".blad canvas.geladen", timeout=30000)
        m.wait_for_timeout(500)
        m.screenshot(path=uit / "11-gsm-lezer.png")
        br.close()

    check("browser: geen fouten in de console", not fouten, fouten)
    return res
