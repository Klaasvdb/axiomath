"""Doorloop in Edge met Playwright, voor test.py --browser. Schermafbeeldingen komen in test/uit/ (niet in git).
PDF.js komt van cdnjs: deze test heeft internet nodig."""
from pathlib import Path

from playwright.sync_api import sync_playwright


def doorloop(url, startcode, uit: Path):
    uit.mkdir(exist_ok=True)
    fouten = []
    res = []

    def check(naam, ok, uitleg=""):
        res.append((naam, bool(ok), uitleg))

    with sync_playwright() as p:
        br = p.chromium.launch(channel="msedge")

        def nieuw(**kw):
            c = br.new_context(viewport={"width": 1400, "height": 900}, **kw)
            pg = c.new_page()
            pg.on("pageerror", lambda e: fouten.append(str(e)))
            pg.on("console", lambda m: m.type == "error" and fouten.append(m.text))
            return c, pg

        # zonder account: de boekenkast en het handboek lezen, geen feedback
        cg, g = nieuw()
        g.goto(url)
        g.wait_for_selector(".kast")
        g.wait_for_function("[...document.querySelectorAll('.boek img')].slice(0, 6).every(i => i.complete && i.naturalWidth > 0)")
        g.screenshot(path=uit / "00-gast-kast.png")
        check("browser: zonder account de boekenkast", g.locator(".boek img").count() > 20)
        g.click("a.boek:has(img) >> nth=0")
        g.wait_for_selector(".boekkop")
        check("browser: zonder account alleen het handboek", g.locator(".editie").count() == 1 and g.locator(".fb, textarea").count() == 0)
        g.screenshot(path=uit / "00-gast-boek.png")
        g.click("a:has-text('Lees') >> nth=0")
        g.wait_for_selector(".blad canvas.geladen", timeout=30000)
        check("browser: zonder account lezen, zonder markeerstift", g.locator("button.markeer").count() == 0)
        g.screenshot(path=uit / "00-gast-lezer.png")
        g.goto(url + "/#/mijn")
        g.wait_for_selector(".welkom")
        check("browser: zonder account naar aanmelden bij mijn feedback", True)
        g.goto(url + "/#/plannen")
        g.wait_for_selector(".plannen")
        check("browser: plannen met zes voorproefjes", g.locator(".proef").count() == 6)
        g.screenshot(path=uit / "00-gast-plannen.png", full_page=True)
        cg.close()

        # beheerder met de startcode
        cb, b = nieuw()
        b.goto(url + "/#/aanmelden")
        b.wait_for_selector(".welkom")
        b.screenshot(path=uit / "01-welkom.png")
        b.click("button[data-k=uitnodiging]")
        b.fill("input[placeholder='abcd-efgh-jkmn']", startcode)
        b.fill("input[autocomplete=name]", "Team Lid")
        b.fill("input[autocomplete=email]", "team@voorbeeld.be")
        b.fill("input[autocomplete=new-password]", "geheim-wachtwoord")
        b.click("button:has-text('Account maken')")
        b.wait_for_selector(".kast")
        b.wait_for_function("[...document.querySelectorAll('.boek img')].slice(0, 6).every(i => i.complete && i.naturalWidth > 0)")
        b.screenshot(path=uit / "02-kast.png")
        check("browser: boekenkast met voorkanten", b.locator(".boek img").count() > 20)

        b.goto(url + "/#/beheer/mensen")
        b.wait_for_selector("input[type=number]")
        b.click("button:has-text('Maak codes')")
        b.wait_for_selector(".code code")
        code = b.locator(".code code").first.inner_text()
        check("browser: uitnodigingscode gemaakt", len(code) == 14, code)
        b.fill("input[placeholder^='Voor wie']", "Ingmar")
        b.click("button:has-text('Maak sleutel')")
        b.wait_for_selector("dialog[open] code")
        sl = b.locator("dialog[open] code").last.inner_text()
        check("browser: sleutel voor Claude", sl.startswith("axm-"), sl)
        b.screenshot(path=uit / "02b-sleutel.png")
        b.click("dialog[open] button:has-text('Sluit')")
        b.wait_for_selector("button:has-text('Intrekken')")
        b.screenshot(path=uit / "02c-mensen.png", full_page=True)

        # leerkracht via de link met code
        cl, l = nieuw()
        l.goto(f"{url}/#/?code={code}")
        l.wait_for_selector(".welkom")
        l.fill("input[autocomplete=name]", "An Leerkracht")
        l.fill("input[autocomplete=email]", "an@voorbeeld.be")
        l.fill("input[autocomplete=new-password]", "nog-een-wachtwoord")
        l.click("button:has-text('Account maken')")
        l.wait_for_selector(".kast")
        l.click("a.boek >> nth=0")
        l.wait_for_selector(".boekkop")
        l.click(".chip.s-didactiek")
        l.fill(".kaart textarea", "Het tempo in hoofdstuk 2 ligt hoog voor pakket 1.")
        l.click("button:has-text('Verstuur')")
        l.wait_for_selector(".fb")
        check("browser: feedback op het handboek", "tempo" in l.locator(".fb").first.inner_text())
        l.screenshot(path=uit / "03-boek.png")

        # lezer met PDF.js
        l.click("a:has-text('Lees en geef feedback') >> nth=0")
        l.wait_for_selector(".blad canvas.geladen", timeout=30000)
        check("browser: PDF.js tekent de pagina's", l.locator(".blad canvas.geladen").count() >= 1)
        l.locator(".blad").nth(1).scroll_into_view_if_needed()
        l.wait_for_selector(".blad[data-n='2'] canvas.geladen", timeout=15000)
        box = l.locator(".blad").nth(1).bounding_box()
        l.mouse.move(box["x"] + box["width"] * .15, box["y"] + box["height"] * .2)
        l.mouse.down()
        l.mouse.move(box["x"] + box["width"] * .7, box["y"] + box["height"] * .3, steps=8)
        l.mouse.up()
        l.wait_for_selector(".nieuw")
        l.wait_for_function("document.querySelector('.nieuw .citaat') && document.querySelector('.nieuw .citaat').textContent !== '…'")
        citaat = l.locator(".nieuw .citaat").inner_text()
        check("browser: citaat uit de tekstlaag", len(citaat) > 5 and "(geen tekst" not in citaat, citaat)
        l.screenshot(path=uit / "04-nieuw.png")
        l.click(".nieuw .chip.s-taal")
        l.fill(".nieuw textarea", "Spatie te veel in de tweede zin.")
        l.click(".nieuw button:has-text('Bewaar')")
        l.wait_for_selector(".markering")
        l.mouse.click(box["x"] + box["width"] * .5, box["y"] + box["height"] * .6)
        l.wait_for_selector(".nieuw")
        l.click(".nieuw .chip.s-fout")
        l.click(".nieuw .segment button:has-text('Dringend')")
        l.fill(".nieuw textarea", "Hier hoort een min.")
        l.click(".nieuw button:has-text('Bewaar')")
        l.wait_for_function("document.querySelectorAll('.markering').length === 2")
        check("browser: twee markeringen op de pagina", l.locator(".markering").count() == 2)
        l.wait_for_timeout(400)
        l.screenshot(path=uit / "05-lezer.png")
        l.keyboard.press("m")
        l.click("button[aria-label=Groter]")
        l.wait_for_timeout(800)
        l.screenshot(path=uit / "06-zoom.png")
        l.click(".tabs button[data-k=inhoud]")
        l.locator(".inhoud-lijst button").nth(3).click()
        l.wait_for_timeout(800)
        check("browser: inhoudstafel springt naar een pagina", int(l.locator(".paginanr input").input_value()) > 2)

        l.goto(url + "/#/algemeen")
        l.wait_for_selector(".kaart textarea")
        l.fill(".kaart textarea", "Mooi idee, maar voorzie ook digitale toetsen.")
        l.click("button:has-text('Verstuur')")
        l.wait_for_selector(".fb")

        # beheerder antwoordt en exporteert
        b.goto(url + "/#/beheer")
        b.wait_for_selector(".fb")
        check("browser: beheer toont 4 open opmerkingen", b.locator(".fb").count() == 4)
        b.locator(".fb textarea").first.fill("Dank je, we passen het aan.")
        b.locator(".fb button:has-text('Stuur')").first.click()
        b.wait_for_timeout(500)
        b.screenshot(path=uit / "07-beheer.png", full_page=True)
        md = b.evaluate("fetch('/api/index.php?r=beheer/export&formaat=md').then(r => r.text())")
        (uit / "export.md").write_text(md, encoding="utf-8")
        check("browser: export bevat het citaat", "> " in md and "Spatie te veel" in md, md[:200])
        b.goto(url + "/#/beheer/overzicht")
        b.wait_for_selector("table")
        b.screenshot(path=uit / "08-overzicht.png")

        l.goto(url + "/#/mijn")
        l.wait_for_selector(".reactie.team")
        check("browser: leerkracht ziet het antwoord", True)
        l.emulate_media(color_scheme="dark")
        l.screenshot(path=uit / "09-mijn-donker.png", full_page=True)

        cm = br.new_context(viewport={"width": 390, "height": 844}, storage_state=cl.storage_state(), is_mobile=True, has_touch=True)
        m = cm.new_page()
        m.on("pageerror", lambda e: fouten.append(str(e)))
        m.goto(url)
        m.wait_for_selector(".kast")
        m.wait_for_timeout(1000)
        m.screenshot(path=uit / "10-gsm-kast.png")
        check("browser: geen horizontaal scrollen op gsm", m.evaluate("document.documentElement.scrollWidth") <= 390)
        m.click("a.boek >> nth=0")
        m.click("a:has-text('Lees en geef feedback') >> nth=0")
        m.wait_for_selector(".blad canvas.geladen", timeout=30000)
        m.wait_for_timeout(500)
        m.screenshot(path=uit / "11-gsm-lezer.png")
        br.close()

    check("browser: geen fouten in de console", not fouten, fouten)
    return res
